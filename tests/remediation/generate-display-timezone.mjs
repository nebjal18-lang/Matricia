// Regenerate the bundled IANA zone from the pinned, checksum-verified Python tzdata wheel.
// Usage: node tests/remediation/generate-display-timezone.mjs <downloaded-wheel>
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const wheel = process.argv[2];
assert.ok(wheel, "Pass the tzdata 2026.5 wheel path");
const checksum = "b683bd1b6659ddcd810ff02ad09ba821d4bf1065072805063eb35c49617905ac";
assert.equal(createHash("sha256").update(readFileSync(wheel)).digest("hex"), checksum);
const data = execFileSync("tar", ["-xOf", wheel, "tzdata/zoneinfo/Africa/Casablanca"]);
function header(at) {
  assert.equal(data.toString("ascii", at, at + 4), "TZif");
  const [gmt, standard, leaps, times, types, chars] = Array.from({ length: 6 }, (_, i) => data.readUInt32BE(at + 20 + i * 4));
  return { gmt, standard, leaps, times, types, chars };
}
function size(h, width) { return h.times * (width + 1) + h.types * 6 + h.chars + h.leaps * (width + 4) + h.standard + h.gmt; }
const start = 44 + size(header(0), 4);
const h = header(start);
const timesAt = start + 44;
const typesAt = timesAt + h.times * 9;
const initial = data.readInt32BE(typesAt);
const transitions = Array.from({ length: h.times }, (_, i) => [Number(data.readBigInt64BE(timesAt + i * 8)), data.readInt32BE(typesAt + data[timesAt + h.times * 8 + i] * 6)]);
const footer = data.toString("ascii", start + 44 + size(h, 8)).trim();
assert.equal(footer, "<+00>0", "A recurring future rule requires generator/runtime support before updating");
assert.deepEqual(transitions.at(-1), [Date.parse("2026-09-20T01:00:00Z") / 1000, 0]);
const file = `// Generated by tests/remediation/generate-display-timezone.mjs. Do not hand-edit.
// IANA tzdb 2026e, Africa/Casablanca (public-domain timezone data).
// Source: https://pypi.org/project/tzdata/2026.5/ (Python-maintained IANA TZif distribution).
// Wheel SHA-256: ${checksum}
// IANA rules: https://github.com/eggert/tz/blob/2026e/africa
export const casablancaTzdbVersion = "2026e";
export const casablancaInitialOffsetSeconds = ${initial};
// UTC transition epoch seconds, then civil offset seconds; final offset continues per TZif footer.
export const casablancaTransitions: readonly (readonly [number, number])[] = [
${transitions.map(([at, offset]) => `  [${at}, ${offset}], // ${new Date(at * 1000).toISOString()}`).join("\n")}
];
`;
writeFileSync("apps/web/modules/shared/lib/format/display-casablanca-data.ts", file);
console.log(`Generated ${transitions.length} transitions, initial=${initial}, footer=${footer}`);
